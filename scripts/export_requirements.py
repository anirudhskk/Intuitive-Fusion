#!/usr/bin/env python3
"""
Export the Requirements Register workbook into the repo so requirements are greppable and traceable.

  python3 scripts/export_requirements.py path/to/Requirements_Register_IntuitiveFusion_vX.Y.xlsx

Writes:
  docs/requirements/functional.csv, non_functional.csv, security.csv, technical.csv, ai_narrative.md
  apps/api/src/modules/<module>/REQUIREMENTS.md  (functional requirements grouped by use case)

Re-run whenever the register is updated so module traceability stays in sync.
"""
import csv
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "requirements"
MODULES = ROOT / "apps" / "api" / "src" / "modules"

# Provisional use-case key from the register's Instructions tab -> API module folder
UC_TO_MODULE = {
    "UC-01": ("intake", "Request intake & conversational AI"),
    "UC-02": ("procurement-plan", "Procurement plan creation & approval"),
    "UC-03": ("rfx", "RFx / tender collaboration & publication"),
    "UC-04": ("tender-portal", "Tender portal & bid submission"),
    "UC-05": ("suppliers", "Supplier registration, onboarding & profile"),
    "UC-06": ("evaluation", "Evaluation, consensus & negotiation/BAFO"),
    "UC-07": ("evaluation-report", "Evaluation report & sourcing recommendation"),
    "UC-08": ("contracts", "Contract award, drafting, legal engagement & signing"),
    "UC-09": ("contract-management", "Contract management, variations & extensions"),
    "UC-10": ("reporting", "Reporting, dashboards & audit reporting"),
    "UC-11": ("migration", "Legacy data migration & onboarding"),
    "UC-12": ("admin", "Administrative configuration & workflow design"),
    "UC-13": ("governance", "Governance, delegation of authority & conflict of interest"),
    "UC-14": ("integrations", "Enterprise integration & platform operations"),
    "UC-15": ("collaboration", "Collaboration, versioning & AI authoring"),
}


def clean(v):
    if v is None:
        return ""
    s = str(v).strip()
    return "" if s == "None" else s


def rows(ws):
    data = [list(r) for r in ws.iter_rows(values_only=True)]
    data = [r for r in data if any(clean(c) for c in r)]
    header = [clean(c) for c in data[0]]
    return header, [[clean(c) for c in r[: len(header)]] for r in data[1:]]


def write_csv(path, header, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(body)


def main(xlsx):
    wb = openpyxl.load_workbook(xlsx, data_only=True)

    # Functional — rows without an ID get a visible placeholder so they can't be silently lost
    h, fr = rows(wb["Functional Requirements"])
    unnumbered = 0
    for r in fr:
        if not r[0] or r[0] == "-":
            unnumbered += 1
            r[0] = f"FR-UNNUMBERED-{unnumbered:02d}"
    write_csv(OUT / "functional.csv", h, fr)

    h_nfr, nfr = rows(wb["Non-Functional Requirements"])
    write_csv(OUT / "non_functional.csv", h_nfr, nfr)

    h_sec, sec = rows(wb["Security Requirements"])
    write_csv(OUT / "security.csv", h_sec, sec)

    # Technical requirements have no IDs in v0.2 — assign provisional TR-nn
    h_tr, tr = rows(wb["Technical Requirements"])
    tr_out = []
    for i, r in enumerate(tr, 1):
        r = r + [""] * (10 - len(r))
        tr_out.append([f"TR-{i:02d}", r[1], r[2], r[3], r[9]])
    write_csv(OUT / "technical.csv", ["ID (provisional)", "Category", "Requirement", "Priority", "Notes"], tr_out)

    # AI tab is free-text narrative from the client — keep it verbatim as markdown context
    ai_lines = [clean(r[0]) for r in wb["AI"].iter_rows(values_only=True) if clean(r[0])]
    (OUT / "ai_narrative.md").write_text(
        "# AI narrative (client-supplied, verbatim from the register's AI tab)\n\n"
        "Not yet decomposed into numbered requirements — see docs/open-decisions.md.\n\n"
        + "\n\n".join(ai_lines)
        + "\n",
        encoding="utf-8",
    )

    # Per-module traceability
    idx = {name: i for i, name in enumerate(h)}
    by_module = {m: {"active": [], "deferred": []} for m, _ in UC_TO_MODULE.values()}
    unassigned = []
    for r in fr:
        uc = r[idx["Related Use Case ID"]]
        prio = r[idx["Priority (MoSCoW)"]]
        if uc not in UC_TO_MODULE:
            unassigned.append(r)
            continue
        module = UC_TO_MODULE[uc][0]
        by_module[module]["deferred" if prio == "Won't" else "active"].append(r)

    for uc, (module, title) in UC_TO_MODULE.items():
        d = MODULES / module
        d.mkdir(parents=True, exist_ok=True)
        lines = [
            f"# {title} — `{module}` module ({uc})",
            "",
            "Generated by `scripts/export_requirements.py` from the Requirements Register. Do not hand-edit;",
            "update the register and re-run the export.",
            "",
            "## In scope",
            "",
        ]
        if not by_module[module]["active"]:
            lines.append("_No functional requirements mapped to this use case yet._")
        for r in by_module[module]["active"]:
            lines += [
                f"### {r[idx['ID']]} · {r[idx['Priority (MoSCoW)']] or 'Priority TBC'}",
                r[idx["Requirement Description"]] or "_Description missing in register_",
                "",
            ]
            if r[idx["Acceptance Criteria"]]:
                lines += [f"**Acceptance:** {r[idx['Acceptance Criteria']]}", ""]
            if "CLIENT QUERY" in r[idx["Notes"]]:
                lines += ["> ⚠ Open client query — see register Notes column.", ""]
        if by_module[module]["deferred"]:
            lines += ["## Deferred / future scope (Won't for this release)", ""]
            for r in by_module[module]["deferred"]:
                lines.append(f"- **{r[idx['ID']]}** — {r[idx['Requirement Description']]}")
            lines.append("")
        (d / "REQUIREMENTS.md").write_text("\n".join(lines), encoding="utf-8")

    with (OUT / "unassigned_functional.md").open("w", encoding="utf-8") as f:
        f.write("# Functional requirements with no use case mapping\n\nNeed a UC-xx (and usually an ID) before they can be built.\n\n")
        for r in unassigned:
            f.write(f"- **{r[0]}** ({r[idx['Category']] or 'no category'}): {r[idx['Requirement Description']] or '(no description)'}\n")

    total = len(fr) + len(nfr) + len(sec) + len(tr_out)
    print(f"Exported {len(fr)} FR ({unnumbered} unnumbered, {len(unassigned)} unassigned), "
          f"{len(nfr)} NFR, {len(sec)} SEC, {len(tr_out)} TR = {total} rows")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
